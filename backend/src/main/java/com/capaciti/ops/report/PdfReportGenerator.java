package com.capaciti.ops.report;

import com.capaciti.ops.common.AppTime;
import com.capaciti.ops.report.ReportDtos.WeeklyReport;
import com.lowagie.text.Document;
import com.lowagie.text.DocumentException;
import com.lowagie.text.Element;
import com.lowagie.text.Font;
import com.lowagie.text.FontFactory;
import com.lowagie.text.PageSize;
import com.lowagie.text.Paragraph;
import com.lowagie.text.Phrase;
import com.lowagie.text.pdf.PdfPCell;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfWriter;
import java.io.ByteArrayOutputStream;
import java.time.format.DateTimeFormatter;
import java.util.Map;
import org.springframework.stereotype.Component;

@Component
public class PdfReportGenerator {

    private static final DateTimeFormatter FMT = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm");

    public byte[] generate(WeeklyReport r) {
        try (ByteArrayOutputStream out = new ByteArrayOutputStream()) {
            Document doc = new Document(PageSize.A4, 48, 48, 48, 48);
            PdfWriter.getInstance(doc, out);
            doc.open();

            Font h1 = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 20);
            Font h2 = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 13);
            Font body = FontFactory.getFont(FontFactory.HELVETICA, 10);
            Font small = FontFactory.getFont(FontFactory.HELVETICA_OBLIQUE, 8);

            doc.add(new Paragraph(r.title(), h1));
            doc.add(new Paragraph("Generated " + FMT.format(r.generatedAt().atZone(AppTime.ZONE))
                    + " (" + AppTime.ZONE + ")", small));
            doc.add(new Paragraph(" "));

            doc.add(new Paragraph("Executive summary", h2));
            doc.add(new Paragraph(r.narrative(), body));
            doc.add(new Paragraph(" "));

            var s = r.summary();
            doc.add(new Paragraph("Key metrics (last " + s.days() + " days)", h2));
            PdfPTable kpis = new PdfPTable(2);
            kpis.setWidthPercentage(100);
            row(kpis, "Total tickets", String.valueOf(s.totalTickets()), body);
            row(kpis, "Open / Resolved", s.openTickets() + " / " + s.resolvedTickets(), body);
            row(kpis, "Avg first response (h)", String.valueOf(s.avgFirstResponseHours()), body);
            row(kpis, "Avg resolution (h)", String.valueOf(s.avgResolutionHours()), body);
            row(kpis, "SLA breaches", s.slaBreaches() + " (" + Math.round(s.slaBreachRate() * 100) + "%)", body);
            doc.add(kpis);
            doc.add(new Paragraph(" "));

            doc.add(new Paragraph("Tickets by category", h2));
            doc.add(table(s.byCategory(), body));
            doc.add(new Paragraph(" "));
            doc.add(new Paragraph("Tickets by priority", h2));
            doc.add(table(s.byPriority(), body));
            doc.add(new Paragraph(" "));

            doc.add(new Paragraph("Insights", h2));
            for (String i : r.insights()) doc.add(new Paragraph("\u2022 " + i, body));
            doc.add(new Paragraph(" "));

            doc.add(new Paragraph("Forecast (next " + r.forecast().horizonDays() + " days)", h2));
            doc.add(new Paragraph(r.forecast().message(), body));
            doc.add(new Paragraph("Projected total: " + r.forecast().projectedTotal() + " tickets.", body));
            doc.add(new Paragraph(" "));
            doc.add(new Paragraph("Narrative generated by an automated system; verify figures before external use.", small));

            doc.close();
            return out.toByteArray();
        } catch (DocumentException | java.io.IOException e) {
            throw new IllegalStateException("Could not generate PDF report", e);
        }
    }

    private static PdfPTable table(Map<? extends Enum<?>, Long> data, Font font) {
        PdfPTable t = new PdfPTable(2);
        t.setWidthPercentage(100);
        data.forEach((k, v) -> row(t, k.name(), String.valueOf(v), font));
        return t;
    }

    private static void row(PdfPTable t, String label, String value, Font font) {
        PdfPCell a = new PdfPCell(new Phrase(label, font));
        PdfPCell b = new PdfPCell(new Phrase(value, font));
        b.setHorizontalAlignment(Element.ALIGN_RIGHT);
        a.setPadding(4);
        b.setPadding(4);
        t.addCell(a);
        t.addCell(b);
    }
}
